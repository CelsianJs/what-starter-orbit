export function findService(id) {
  return findServiceStrict(id) || services[0];
}

export function findServiceStrict(id) {
  return services.find((service) => service.id === id);
}

export function minutes(ms) {
  return Math.round(ms / 60000);
}

export function endTime(start, duration) {
  return new Date(new Date(start).getTime() + duration * 60000).toISOString();
}

export function displayTime(value) {
  return new Intl.DateTimeFormat('en-US', { hour: 'numeric', minute: '2-digit', timeZone: timezone }).format(new Date(value));
}

export function displayDate(value) {
  return new Intl.DateTimeFormat('en-US', { weekday: 'short', month: 'short', day: 'numeric', timeZone: timezone }).format(new Date(`${value}T12:00:00-04:00`));
}

export function slotDate(value) {
  return value.slice(0, 10);
}

export function overlaps(aStart, aDuration, bStart, bDuration) {
  const a0 = new Date(aStart).getTime();
  const a1 = a0 + aDuration * 60000;
  const b0 = new Date(bStart).getTime();
  const b1 = b0 + bDuration * 60000;
  return a0 < b1 && b0 < a1;
}

export function createIcs(reservation) {
  const service = findService(reservation.serviceId);
  const stamp = (date) => new Date(date).toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');
  return [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//What Framework//Orbit Starter//EN',
    'BEGIN:VEVENT',
    `UID:${reservation.id}@orbit.local`,
    `DTSTAMP:${stamp(new Date().toISOString())}`,
    `DTSTART:${stamp(reservation.start)}`,
    `DTEND:${stamp(endTime(reservation.start, service.duration))}`,
    `SUMMARY:${service.name} at Orbit Studio`,
    'DESCRIPTION:Local demo reservation generated by Orbit.',
    'END:VEVENT',
    'END:VCALENDAR',
  ].join('\r\n');
}
